function areaForDomain(
  domain: Exclude<ScientificLibraryDomain, "PROTOCOL">,
): ScientificLibraryArea {
  if (domain === "EXERCISE" || domain === "TRAINING_METHOD" || domain === "ASSESSMENT") {
    return "PERFORMANCE";
  }
  if (domain === "POSTURAL_CHANGE" || domain === "POSTURAL_CONDITION") {
    return "POSTURAL";
  }
  return "NUTRITION";
}

